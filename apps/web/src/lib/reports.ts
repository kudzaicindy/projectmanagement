function toCsv(headers: string[], rows: string[][]) {
  const escape = (v: string) => `"${v.replace(/"/g, '""')}"`;
  return [headers, ...rows].map((row) => row.map(escape).join(',')).join('\r\n');
}

export function downloadPortfolioSummaryCsv(
  projects: Project[],
  properties: Property[],
  generatedBy: User,
) {
  const summary = getPortfolioBudgetSummary(projects);
  const meta = [
    ['Alamait EstatePM — Portfolio Summary Report'],
    ['Generated', new Date().toLocaleString()],
    ['Generated by', `${generatedBy.name} (${roleLabels[generatedBy.role]})`],
    [],
    ['Portfolio KPIs'],
    ['Properties', String(properties.length)],
    ['Projects', String(projects.length)],
    ['Approved budget (USD)', formatUsd(summary.approved)],
    ['Spent (derived)', formatUsd(summary.spent)],
    ['Remaining', formatUsd(summary.remaining)],
    [],
  ];

  const headers = [
    'Project',
    'Property',
    'Type',
    'Status',
    'Budget USD',
    'Schedule %',
    'Timeline %',
    'Tracking',
    'Start',
    'End',
    'Tasks',
    'Documents',
  ];

  const rows = projects.map((p) => {
    const t = getProjectTracking(p);
    return [
      p.name,
      p.property?.name ?? '',
      projectTypeLabels[p.type],
      projectStatusLabels[p.status],
      p.budgetUsd ? formatUsd(p.budgetUsd) : '',
      String(t.schedulePct),
      String(t.timelinePct),
      t.trackingLabel,
      formatDate(p.startDate),
      formatDate(p.endDate),
      String(t.taskCount),
      String(p._count?.documents ?? 0),
    ];
  });

  const csv = [...meta.map((r) => r.join(',')), toCsv(headers, rows)].join('\r\n');
  triggerDownload(new Blob([csv], { type: 'text/csv;charset=utf-8' }), `alamait-portfolio-summary-${Date.now()}.csv`);
}

export function downloadProjectTrackingCsv(projects: Project[]) {
  const headers = [
    'Project',
    'Property',
    'Status',
    'Schedule %',
    'Timeline %',
    'Delta',
    'Tracking',
    'Overdue',
    'Tasks complete',
    'Tasks total',
    'Blocked tasks',
    'Budget util %',
  ];
  const rows = projects.map((p) => {
    const t = getProjectTracking(p);
    return [
      p.name,
      p.property?.name ?? '',
      projectStatusLabels[p.status],
      String(t.schedulePct),
      String(t.timelinePct),
      String(t.scheduleDelta),
      t.trackingLabel,
      t.isOverdue ? 'Yes' : 'No',
      String(t.tasksComplete),
      String(t.taskCount),
      String(t.tasksBlocked),
      String(t.budgetUtilPct),
    ];
  });
  const preamble = [
    'Alamait EstatePM — Project Tracking Report',
    `Generated,${new Date().toLocaleString()}`,
    '',
  ];
  const csv = [...preamble, toCsv(headers, rows)].join('\r\n');
  triggerDownload(new Blob([csv], { type: 'text/csv;charset=utf-8' }), `alamait-project-tracking-${Date.now()}.csv`);
}

export function downloadPortfolioHealthCsv(portfolioProjects: PortfolioProjectHealth[]) {
  const headers = [
    'Project',
    'Phase',
    'Progress %',
    'Status',
    'CapEx',
    'Spent',
    'Forecast',
    'Variance',
    'Cash 30d',
    'Notes',
  ];
  const rows: string[][] = [];
  for (const proj of portfolioProjects) {
    const level = healthLabel(proj);
    if (proj.summary) {
      const s = proj.summary;
      rows.push([
        proj.name,
        'Portfolio total',
        String(s.percentComplete),
        s.status,
        s.budgetCapex != null ? formatUsd(s.budgetCapex) : '',
        s.actualSpend != null ? formatUsd(s.actualSpend) : '',
        s.forecastTotal != null ? formatUsd(s.forecastTotal) : '',
        s.variance != null ? formatVariance(s.variance) : '',
        s.cashFlowNeed30d != null ? formatUsd(s.cashFlowNeed30d) : '',
        s.notes ?? '',
      ]);
    }
    for (const ph of proj.phases) {
      rows.push([
        proj.name,
        ph.name,
        String(ph.percentComplete),
        ph.status,
        ph.budgetCapex != null ? formatUsd(ph.budgetCapex) : '',
        ph.actualSpend != null ? formatUsd(ph.actualSpend) : '',
        ph.forecastTotal != null ? formatUsd(ph.forecastTotal) : '',
        ph.variance != null ? formatVariance(ph.variance) : '',
        ph.cashFlowNeed30d != null ? formatUsd(ph.cashFlowNeed30d) : '',
        ph.notes ?? '',
      ]);
    }
    rows.push([proj.name, `Health: ${level}`, '', '', '', '', '', '', '', '']);
  }
  const preamble = [
    'Alamait EstatePM — QA Portfolio Health (executive tracking)',
    `Generated,${new Date().toLocaleString()}`,
    '',
  ];
  const csv = [...preamble, toCsv(headers, rows)].join('\r\n');
  triggerDownload(new Blob([csv], { type: 'text/csv;charset=utf-8' }), `alamait-portfolio-health-${Date.now()}.csv`);
}

function htmlEscape(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function printPortfolioReport(
  projects: Project[],
  properties: Property[],
  generatedBy: User,
  audit: AuditLog[] = [],
  portfolioProjects: PortfolioProjectHealth[] = [],
) {
  const summary = getPortfolioBudgetSummary(projects);
  const overdue = projects.filter((p) => getProjectTracking(p).isOverdue);
  const atRiskHealth = portfolioProjects.filter((p) => healthLabel(p) === 'at_risk');

  const projectRows = projects
    .map((p) => {
      const t = getProjectTracking(p);
      return `<tr>
        <td>${htmlEscape(p.name)}</td>
        <td>${htmlEscape(p.property?.name ?? '—')}</td>
        <td>${projectStatusLabels[p.status]}</td>
        <td>${t.schedulePct}%</td>
        <td>${t.trackingLabel}</td>
        <td>${p.budgetUsd ? formatUsd(p.budgetUsd) : '—'}</td>
        <td>${formatDate(p.endDate)}</td>
      </tr>`;
    })
    .join('');

  const healthRows = portfolioProjects
    .map((p) => {
      const m = getProjectMetrics(p);
      return `<tr>
        <td>${htmlEscape(p.name)}</td>
        <td>${healthLabel(p)}</td>
        <td>${m.progress}%</td>
        <td>${formatUsd(m.budget)}</td>
        <td>${formatVariance(m.variance)}</td>
      </tr>`;
    })
    .join('');

  const auditRows =
    audit.length > 0
      ? audit
          .slice(0, 25)
          .map(
            (log) => `<tr>
        <td>${new Date(log.createdAt).toLocaleString()}</td>
        <td>${htmlEscape(log.user?.name ?? '—')}</td>
        <td>${log.action}</td>
        <td>${log.entityType}</td>
      </tr>`,
          )
          .join('')
      : '';

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>Alamait EstatePM — Portfolio Report</title>
  <style>
    body { font-family: system-ui, sans-serif; color: #111; margin: 32px; font-size: 12px; }
    h1 { font-size: 20px; margin: 0 0 4px; }
    .meta { color: #666; margin-bottom: 24px; }
    h2 { font-size: 14px; margin: 24px 0 8px; border-bottom: 1px solid #eee; padding-bottom: 4px; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 16px; }
    th, td { text-align: left; padding: 6px 8px; border-bottom: 1px solid #eee; }
    th { font-size: 10px; text-transform: uppercase; color: #666; }
    .kpis { display: grid; grid-template-columns: repeat(4, 1fr); gap: 12px; margin: 16px 0; }
    .kpi { border: 1px solid #eee; border-radius: 8px; padding: 12px; }
    .kpi label { font-size: 10px; color: #888; display: block; }
    .kpi strong { font-size: 16px; }
    @media print { body { margin: 16px; } }
  </style>
</head>
<body>
  <h1>Alamait EstatePM — Portfolio Report</h1>
  <p class="meta">Generated ${new Date().toLocaleString()} · ${htmlEscape(generatedBy.name)} (${roleLabels[generatedBy.role]})</p>

  <div class="kpis">
    <div class="kpi"><label>Properties</label><strong>${properties.length}</strong></div>
    <div class="kpi"><label>Projects</label><strong>${projects.length}</strong></div>
    <div class="kpi"><label>Portfolio budget</label><strong>${formatUsd(summary.approved)}</strong></div>
    <div class="kpi"><label>Overdue projects</label><strong>${overdue.length}</strong></div>
  </div>

  <h2>Projects (EstatePM)</h2>
  <table>
    <thead><tr><th>Project</th><th>Property</th><th>Status</th><th>Schedule</th><th>Tracking</th><th>Budget</th><th>Due</th></tr></thead>
    <tbody>${projectRows || '<tr><td colspan="7">No projects</td></tr>'}</tbody>
  </table>

  <h2>Portfolio health (QA / executive)</h2>
  <p class="meta">${atRiskHealth.length} project(s) at risk in executive tracking dataset.</p>
  <table>
    <thead><tr><th>Site</th><th>Health</th><th>Progress</th><th>CapEx</th><th>Variance</th></tr></thead>
    <tbody>${healthRows}</tbody>
  </table>

  ${
    auditRows
      ? `<h2>Recent audit (last 25)</h2><table><thead><tr><th>When</th><th>User</th><th>Action</th><th>Entity</th></tr></thead><tbody>${auditRows}</tbody></table>`
      : ''
  }

  <p class="meta" style="margin-top:32px">EstatePM · Confidential — for internal Alamait use</p>
  <script>window.onload = () => { window.print(); };</script>
</body>
</html>`;

  const w = window.open('', '_blank', 'noopener,noreferrer');
  if (!w) {
    alert('Allow pop-ups to open the printable report.');
    return;
  }
  w.document.write(html);
  w.document.close();
}
